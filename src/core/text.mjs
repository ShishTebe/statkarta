// Текст и даты. Канон: буква «е» вместо «е с точками», среднее тире, даты ДД.ММ.ГГГГ.

export function normText(s) {
  return String(s ?? '').replace(/[\u0451\u0401]/g, (c) => (c === '\u0451' ? 'е' : 'Е')).replace(/\u2014/g, '–');
}

export function isoToRu(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(iso ?? '');
  return m ? `${m[3]}.${m[2]}.${m[1]}` : '';
}

export function ruToIso(ru) {
  const m = /^\s*(\d{1,2})\.(\d{1,2})\.(\d{4})\s*$/.exec(ru ?? '');
  if (!m) return null;
  const [d, mo, y] = [Number(m[1]), Number(m[2]), Number(m[3])];
  const dt = new Date(Date.UTC(y, mo - 1, d));
  if (dt.getUTCFullYear() !== y || dt.getUTCMonth() !== mo - 1 || dt.getUTCDate() !== d) return null;
  return `${y}-${String(mo).padStart(2, '0')}-${String(d).padStart(2, '0')}`;
}

export function todayIso() {
  const d = new Date();
  return `${d.getFullYear()}-${String(d.getMonth() + 1).padStart(2, '0')}-${String(d.getDate()).padStart(2, '0')}`;
}

export function shortLabel(label, max = 90) {
  const s = normText(label).replace(/\s+/g, ' ').trim();
  return s.length > max ? `${s.slice(0, max - 1).trimEnd()}…` : s;
}

// «КАТЕГОРИЯ ПРЕСТУПЛЕНИЯ» → «Категория преступления»; смешанный регистр не трогаем
const ABBR = new Set(['рф', 'ук', 'упк', 'коап', 'окато', 'оквэд', 'окопф', 'иц', 'гиац', 'овд', 'снг', 'фсб', 'фссп', 'фсин', 'фскн', 'опк', 'мвд', 'ск', 'гп', 'пс', 'гпн', 'фпс', 'нрд', 'рд', 'ссср', 'ип', 'гу', 'цфо', 'сзфо', 'юфо', 'пфо', 'уфо', 'сфо', 'дфо', 'скфо', 'пао', 'ао', 'ооо', 'фгуп', 'зато', 'днр', 'лнр', 'чоп', 'бомж', 'сми', 'ит', 'итт', 'абд', 'иу', 'сизо', 'кусп', 'крсп', 'вуд', 'жкх', 'ндс', 'сша', 'ес', 'оон', 'апк', 'гибдд', 'мчс', 'кпп', 'фкпп', 'окпп', 'бстм', 'гут', 'гусб', 'ур', 'орч', 'убк', 'гупэ', 'гунк', 'уогз', 'нцб', 'собр', 'стм', 'фас', 'цб', 'сфр', 'итт', 'вфу', 'опг', 'осн', 'пдн', 'ооо', 'нко', 'снт', 'тсж', 'ифнс', 'фнс', 'фтс', 'уфссп', 'зато', 'гпк', 'ик', 'лиу', 'вк', 'пфр', 'фсс', 'фомс']);
export function sentenceCase(label) {
  const s = normText(label).replace(/\s+/g, ' ').trim();
  // целые слова заглавными (кроме аббревиатур и инициалов с точкой) – в обычный регистр
  if (!/[А-ЯA-Z]{3,}/.test(s)) return s.charAt(0).toUpperCase() + s.slice(1);
  const low = s.replace(/(?<![А-Яа-яA-Za-z])[А-ЯA-Z][А-ЯA-Z-]*(?![а-яa-z])/g, (w, off) => {
    if (ABBR.has(w.toLowerCase()) || s[off + w.length] === '.' && w.length <= 2) return w;
    return w.toLowerCase();
  });
  return low.charAt(0).toUpperCase() + low.slice(1);
}

// Наименование реквизита для показа (сверенное с бланком – как есть): без первого варианта кода, приклеенного разметкой, и без хвостового номера
export function displayLabel(r) {
  if (r.label_status === 'verified') return normText(r.label);
  let l = sentenceCase(r.label ?? '');
  const first = r.options?.[0]?.value ? normText(r.options[0].value).toLowerCase() : null;
  const low = l.toLowerCase();
  if (first && low.includes(':') && low.endsWith(first)) l = l.slice(0, l.lastIndexOf(':'));
  else if (r.options?.length && r.raw && l.length < 40 && !['corrected', 'derived'].includes(r.label_status)) {
    const fromRaw = normText(r.raw).replace(/\(\d{1,6}\)/g, '').replace(/_+/g, ' ').replace(/[«“"]\s*[»”"]/g, ' ').replace(/\s+([,.;:])/g, '$1').replace(/\s+/g, ' ').trim();
    if (fromRaw.length > l.length) l = sentenceCase(fromRaw.length > 140 ? `${fromRaw.slice(0, fromRaw.lastIndexOf(' ', 138))}…` : fromRaw);
  }
  return l.replace(/\s+\d+(?:\.\d+)*\s*$/, '').replace(/[\s:(«“]+$/, '');
}

